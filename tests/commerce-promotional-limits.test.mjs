test('promotion limit is staff-controlled with independent review, no customer writes',()=>{
 assert.match(migration,/revoke all on public\.commerce_offer_purchase_limits from public,anon,authenticated,service_role/)
 assert.match(migration,/alter table public\.commerce_offer_purchase_limits enable row level security/)
 assert.match(migration,/private\.commerce_admin\(\)/)
 assert.match(migration,/private\.has_role\(auth\.uid\(\),'super_admin'\)/)
 assert.match(migration,/v_rule\.requested_by=auth\.uid\(\)/)
 assert.match(migration,/status='superseded'/)
 assert.match(migration,/public\.audit_events/)
 assert.match(admin,/Request a promotion limit/)
 assert.match(admin,/independent review/i)
 assert.match(action,/commerce_request_purchase_limit/)
 assert.match(action,/commerce_review_purchase_limit/)
})
test('per-account cap applies through cart, quote and final checkout',()=>{
 for(const name of ['commerce_cart_limit_guard','commerce_quote_limit_guard','commerce_order_limit_guard'])
  assert.match(migration,new RegExp('create trigger '+name.replace('_guard','_before')))
 assert.match(migration,/join public\.commerce_orders ord on ord\.id=i\.order_id/)
 assert.match(migration,/ord\.customer_id=p_customer/)
 assert.match(migration,/l\.campaign_key=r\.campaign_key/)
 assert.match(migration,/v_used\+p_quantity>r\.account_cap/)
 assert.match(migration,/pg_advisory_xact_lock/)
 assert.match(migration,/public\.commerce_order_items/)
 assert.match(sqlTest,/Same customer cannot reopen offer in new cart/)
 assert.match(sqlTest,/Second same-campaign offer cannot evade cap/)
 assert.match(sqlTest,/Idempotent checkout retry/)
})
test('household cap requires operator-verified address and household identity, not GPS',()=>{
 assert.match(migration,/verification_status='operator_verified'/)
 assert.match(migration,/commerce_verified_household_members/)
 assert.match(migration,/Verified household required for this limited offer/)
 assert.match(migration,/v_used\+p_quantity>r\.household_cap/)
 assert.match(migration,/commerce_household_verified/)
 assert.doesNotMatch(migration,/gps.latitude|gps.longitude|household_name/)
 assert.match(sqlTest,/Second account of same verified family denied/)
})
