import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const shell=read('components/admin-shell.tsx')
const page=read('app/admin/products/page.tsx')
const wizard=read('components/admin-product-create-wizard.tsx')
const css=read('app/site-product-management.css')
const layout=read('app/layout.tsx')

test('only Product Management opts into the storefront design skin without removing admin role access',()=>{
 assert.match(page,/<AdminShell variant="product">/)
 assert.match(shell,/variant\s*=\s*'default'/)
 assert.match(shell,/isProduct \? ' product-management-shell'/)
 assert.match(shell,/SITE_TAGLINE_EN/)
 assert.match(shell,/SITE_TAGLINE_BN/)
 assert.match(shell,/\/super-admin/)
 assert.match(shell,/\/admin\/products/)
 assert.match(layout,/import '\.\/site-product-management\.css'/)
 assert.match(css,/\.product-management-shell/)
 assert.doesNotMatch(css,/^\s*\.card\s*\{/m,'must not change all cards site-wide')
})
test('navigation uses concise no-wrap six-step pills with responsive container queries',()=>{
 assert.match(wizard,/const tabs=\[/)
 for(const label of ['Product & SKU','Specs','SEO · EN/BN','AEO / GEO','Media','Review']) assert.ok(wizard.includes(label))
 assert.match(wizard,/product-wizard-steps/)
 assert.match(wizard,/product-wizard-step-label/)
 assert.match(wizard,/aria-current=\{step===i\?'step':undefined\}/)
 assert.match(wizard,/role="progressbar"/)
 assert.match(css,/white-space:nowrap/)
 assert.match(css,/repeat\(6,minmax\(0,1fr\)\)/)
 assert.match(css,/repeat\(3,minmax\(0,1fr\)\)/)
 assert.match(css,/repeat\(2,minmax\(0,1fr\)\)/)
 assert.match(css,/@container \(min-width:790px\)/)
 assert.match(css,/min-height:40px/)
})
test('product form remains a single six-step creation and protected actions unchanged',()=>{
 assert.equal((wizard.match(/<form\b/g)??[]).length,1)
 assert.match(wizard,/createProductWithSeo/)
 assert.match(wizard,/title_bn/)
 assert.match(wizard,/ProductImageInput/)
 assert.match(wizard,/Create product & save SEO draft/)
 assert.match(page,/AdminProductLifecycle/)
 assert.match(page,/AdminProductSeoEditor/)
})
test('new styling is accessible and preserves storefront light/dark modes',()=>{
 assert.match(css,/prefers-reduced-motion:reduce/)
 assert.match(css,/focus-visible/)
 assert.match(css,/html\[data-theme="dark"\]/)
 assert.match(css,/--gloss-rim/)
 assert.match(css,/--theme-text/)
 assert.match(css,/--theme-accent/)
 assert.match(css,/--theme-input/)
})
