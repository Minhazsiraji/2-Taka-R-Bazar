import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const page=read('app/admin/easy-business/page.tsx')
const calculator=read('components/easy-tier-form.tsx')
const readiness=read('lib/easy-business-readiness.ts')
const poolActions=read('app/actions/pools.ts')
const pilot=read('app/actions/pilot.ts')
const ops=read('app/actions/admin.ts')
const publication=read('app/actions/storefront-publication.ts')
const shell=read('components/admin-shell.tsx')
const dash=read('app/admin/page.tsx')

test('Easy Business is the visible default entry, without new branding or storefront UI',()=>{
 assert.match(shell,/\/admin\/easy-business','Easy Business'/)
 assert.match(dash,/Open Easy Business/)
 assert.match(page,/AdminShell/)
 assert.match(page,/card/g)
 assert.match(page,/btn-primary/)
 assert.match(page,/btn-secondary/)
 assert.match(page,/Get a product ready to sell/)
 assert.match(page,/Add a product/)
 assert.match(page,/Choose where to sell/)
 assert.match(page,/Prepare:/)
 assert.match(page,/Open & show on storefront/)
 assert.doesNotMatch(page,/new.*brand|replace.*logo|font-family|background-color/)
})

test('one guided Pool uses already secured mutations and returns inline after each step',()=>{
 for(const action of ['createPoolV2','updateDraftPool','setPoolPickupOptions','addPoolItem','setPoolStatus','publishStorefrontPool']){
  assert.match(page,new RegExp('action=\\{'+action+'\\}'))
 }
 assert.match(calculator,/action=\{enterPlanningTier\}/)
 assert.match(poolActions,/requireAdmin\(\)/)
 assert.match(pilot,/requireAdmin\(\)/)
 assert.match(ops,/requireAdmin\(\)/)
 assert.match(publication,/requireAdmin\(\)/)
 assert.match(poolActions,/return_to'\)==='\/admin\/easy-business'/)
 assert.match(ops,/return_to'\)==='\/admin\/easy-business'/)
 assert.match(pilot,/return_to'\)==='\/admin\/easy-business'/)
 assert.match(publication,/return_to'\)==='\/admin\/easy-business'/)
 assert.match(poolActions,/base\.includes\('\?'\)\?'\&':'\?'/)
 assert.match(page,/return_to" value="\/admin\/easy-business"/)
})

test('pricing input is explicit, computed only and delegated to existing validation',()=>{
 assert.match(calculator,/Supplier price \/ unit/)
 assert.match(calculator,/Unlock at units \(not customers\)/)
 assert.match(calculator,/Total landed cost/)
 assert.match(calculator,/Customer saving vs\. benchmark/)
 assert.match(calculator,/Gross contribution \(not net profit\)/)
 assert.match(calculator,/Math\.round\(\(q\+d\+h\)\*100\)\/100/)
 assert.match(calculator,/c>=landed&&c<=benchmark/)
 assert.match(calculator,/name="landed_unit_price"/)
 assert.match(pilot,/ceiling<landed/)
 assert.match(pilot,/existingTiers\?\?\[\]\)\.length>=3/)
 assert.doesNotMatch(calculator,/updateLedger|updateJournal|paySupplier|refundCustomer|postEntry/i)
})
test('Pool stage gating remains backend-authoritative and scheduled is not live',()=>{
 assert.match(page,/poolLaunchChecklist\(/)
 assert.match(readiness,/supplierItemTierCounts\.every\(q=>q>=2\)/)
 assert.match(readiness,/pool\.status==='draft'/)
 assert.match(readiness,/pool\.opens_at!\)>Date\.now\(\)/)
 assert.match(page,/The database still performs all final security and commercial validation/)
 assert.match(page,/Production purchases/)
 assert.match(ops,/admin_set_pool_status/)
 assert.match(publication,/admin_publish_storefront_pool/)
 assert.match(page,/Customer pickup choices/)
 assert.match(page,/Publish on Home/)
 assert.match(page,/Cancelled Pools are archived, not reopened automatically/)
 assert.match(page,/new.*Pool/)
 assert.doesNotMatch(page,/service_role|supabaseAdmin|DISABLE_CHECKOUT|enablePurchase|bypass_approval/)
})
