 assert.ok(home.includes('className="mhome-hero-second"'))
 assert.ok(home.includes('className="mhome-hero-controls"'))
 assert.ok(home.includes('className="mhome-dots"'))
 assert.ok(!home.includes('className="mhome-hero-art"'))
 assert.match(home,/GROUP_DEAL'\)\.slice\(0,6\)/)
 assert.match(home,/className="mhome-area-picker"/)
 assert.doesNotMatch(home,/Ask for Price/)
 assert.match(css,/url\('\/2tbr-app-hero\.jpg'\)/)
 assert.match(css,/background-size:100% 100%!important/)
 assert.match(css,/grid-template-columns:repeat\(4,minmax\(0,1fr\)\)!important/)
