import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const data=read('lib/hero-messages.ts')
const hero=read('components/animated-hero-messages.tsx')
const storefront=read('components/public-marketplace.tsx')
const header=read('components/public-header.tsx')
const showcase=read('components/featured-pool-showcase.tsx')
const pools=read('lib/featured-pools.ts')
const style=read('app/marketplace-hero-motion.css')
const layout=read('app/layout.tsx')
const brand=read('lib/site.ts')

test('first headline and subheadline are verbatim approved copy; remaining three pairs are distinct',()=>{
 assert.match(data,/Smart people make smart decisions\./)
 assert.match(data,/Buy together, save together\./)
 assert.match(data,/Invite your neighbours and friends\. Join the Pool together to unlock wholesale prices\./)
 for(const phrase of ['A smarter way to shop.','A better way to save.','Your neighbours. Your Pool.','Your savings.','Buying together makes','every taka count.']){
  assert.ok(data.includes(phrase),phrase)
 }
 assert.equal((data.match(/key:'(decisions|smarter|neighbours|taka)'/g)||[]).length,4)
 assert.match(data,/bn:/)
 assert.match(brand,/Smart shopping\. Real savings!/)
 assert.match(brand,/একসাথে কিনি, কম দামে পাই!/)
})
test('motion switches only marketing copy every 7 seconds; buttons and Pool showcase remain stable',()=>{
 assert.match(data,/HERO_ROTATION_MS=7000/)
 assert.match(hero,/window\.setInterval/)
 assert.match(hero,/window\.clearInterval/)
 assert.match(hero,/document\.visibilityState==='visible'/)
 assert.match(hero,/onMouseEnter=\{\(\)=>setPaused\(true\)\}/)
 assert.match(hero,/onFocusCapture/)
 assert.match(hero,/prefers-reduced-motion: reduce/)
 assert.match(hero,/HERO_MESSAGES\.map/)
 assert.match(hero,/market-hero-message-dots/)
 assert.match(hero,/market-hero-message-arrows/)
 assert.match(hero,/aria-live="off"/)
 assert.match(storefront,/<AnimatedHeroMessages language=\{language\}\/\>/)
 assert.match(storefront,/<FeaturedPoolShowcase pools=\{heroPools\}/)
 const motionIndex=storefront.indexOf('<AnimatedHeroMessages')
 const actionsIndex=storefront.indexOf('className="market-hero-actions"')
 assert.ok(motionIndex<actionsIndex,'hero actions stay outside the moving text')
 assert.match(style,/\.market-hero-message\{[\s\S]*?animation:market-hero-enter \.5s/)
 assert.match(style,/@media\(prefers-reduced-motion:reduce\)/)
 assert.match(style,/market-hero-message-frame/)
})
