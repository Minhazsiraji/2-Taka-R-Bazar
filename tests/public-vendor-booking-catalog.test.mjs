import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=(name)=>readFileSync(name,'utf8')
const migration=read('supabase/migrations/20261021202000_public_vendor_booking_catalog.sql')
const home=read('app/page.tsx')
const publicMarket=read('components/public-marketplace.tsx')
const cards=read('components/mobile-marketplace-home.tsx')
const dataView=read('lib/approved-card-view.ts')
const catalog=read('components/published-products-page.tsx')
const detail=read('app/vendor-products/[id]/page.tsx')
const existingGate=read('lib/commerce/server.ts')

test('only the real six audited on-demand products publish, not cost or inventory',()=>{
 assert.match(migration,/source_audit_id bigint not null/)
 assert.match(migration,/v_audit bigint:=958/)
 assert.match(migration,/v_vendor uuid:='0814a10b-f4dd-4239-a267-aeddadb355d6'/)
 assert.match(migration,/v_count<>6 or v_sum<>6220/)
 assert.match(migration,/d\.confirmation_policy='confirm_per_order'/)
 assert.match(migration,/d\.supplier_handover_days=1/)
 assert.match(migration,/d\.status='draft' and d\.supply_mode='on_demand'/)
 assert.match(migration,/p\.active and not p\.is_demo/)
 assert.match(migration,/and d\.proposed_sale_price=l\.approved_unit_price/)
 assert.match(migration,/owner_approved_pilot_vendor_catalog_published/)
 assert.doesNotMatch(migration,/insert into public.commerce_offers|insert into public.own_product_inventory|insert into public.finance_journals|update private.commerce_configuration/)
})

test('public catalog RPC exposes only owner-approved public display fields',()=>{
 assert.match(migration,/alter table public.pilot_vendor_product_listings enable row level security/)
 assert.match(migration,/revoke all on public.pilot_vendor_product_listings from public,anon,authenticated,service_role/)
 assert.match(migration,/security definer set search_path=''/)
 assert.match(migration,/grant execute on function public.get_public_pilot_vendor_catalog\(uuid\) to anon,authenticated/)
 const signature=migration.match(/returns table\(([\s\S]*?)\)\s*language sql/)
 assert.ok(signature)
 assert.doesNotMatch(signature[1],/vendor_unit_cost|account_number|stock_quantity|owner_email|audit_metadata/)
 assert.match(migration,/where l\.published/)
})

test('live customer homepage and all-products page reuse the approved cards with public catalog data',()=>{
 assert.match(home,/get_public_launch_catalog/)
 assert.match(home,/vendorProducts=\{vendorProducts\}/)
 assert.match(publicMarket,/vendorProducts=\{vendorProducts\}/)
 assert.match(dataView,/data\.vendorProducts/)
 assert.match(cards,/vendorProducts/)
 assert.match(read('components/home-card-preview.tsx'),/\/preview-live\/product\//)
 assert.match(read('components/home-card-preview.tsx'),/Add to cart/)
 assert.match(dataView,/stock:null/)
 assert.match(catalog,/LivePreviewHomeCards/)
 assert.match(catalog,/vendorProducts/)
 assert.match(detail,/get_public_pilot_vendor_catalog/)
 assert.match(detail,/\/pilot-book\?product=/)
 assert.match(detail,/Final product price, supply availability/)
 assert.match(existingGate,/VERCEL_ENV==='preview'/)
})
