import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const client=read('components/admin-product-create-wizard.tsx')
const server=read('app/actions/product-wizard.ts')
const page=read('app/admin/products/page.tsx')
const uat=read('tests/account-security-browser-uat.mjs')

test('create wizard intercepts HTML submit so server validation NEVER causes a form reload',()=>{
 assert.match(client,/onSubmit=\{handleSubmit\}/)
 assert.match(client,/event\.preventDefault\(\)/)
 assert.match(client,/new FormData\(form\)/)
 assert.match(client,/startTransition\(async\(\)=>/)
 assert.match(client,/setIssue\(\{message:result\.message/)
 assert.doesNotMatch(client,/<form action=/)
})
test('server-side product creation returns errors instead of redirecting',()=>{
 const create=server.slice(server.indexOf('export async function createProductWithSeo'),server.indexOf('export async function deleteUnusedProduct'))
 assert.match(create,/return \{ok:false,message:error\.message/)
 assert.match(create,/instanceof WizardValidationError/)
 assert.match(create,/return \{ok:true,message:/)
 assert.doesNotMatch(create,/\bfail\(/)
 assert.doesNotMatch(create,/\bdone\(/)
 assert.doesNotMatch(create,/\bredirect\(/)
 assert.match(server,/if\(!url&&!file&&!alt_en&&!alt_bn\)continue/)
 assert.match(server,/select a PC file, add an approved HTTPS URL, or clear both optional alt texts/)
 assert.match(server,/invalid\(.*urlField,4\)/)
})
test('browser tab draft autosave recovers EN/BN inputs and FAQ but never stores image bytes',()=>{
 assert.match(page,/userId=\{user\.id\}/)
 assert.match(client,/sessionStorage\.setItem/)
 assert.match(client,/sessionStorage\.getItem/)
 assert.match(client,/sessionStorage\.removeItem/)
 assert.match(client,/element\.type==='file'\)continue/)
 assert.match(client,/Browsers|browsers do not restore selected files/)
 assert.match(client,/Clear draft \/ New product/)
 assert.match(client,/window\.confirm/)
 assert.match(client,/form\.reset\(\)/)
 assert.match(client,/if\(!result\.ok\)/)
 assert.match(uat,/Product wizard failed-save retention, refresh recovery and successful retry PASS/)
 assert.match(uat,/longEnglish/)
 assert.match(uat,/longBangla/)
 assert.match(uat,/marketing_alt_bn_1/)
})
