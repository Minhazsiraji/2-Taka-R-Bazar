import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const wizard=read('components/admin-product-create-wizard.tsx')
const page=read('app/admin/products/page.tsx')
const actions=read('app/actions/product-wizard.ts')
const sql=read('supabase/migrations/20261015031616_product_wizard_safe_delete_issue86.sql')
const lifecycle=read('components/admin-product-lifecycle.tsx')

test('single guided six-step Create Product form holds both master and bilingual SEO data',()=>{
 assert.match(page,/<AdminProductCreateWizard key=\{user.id\} userId=\{user.id\}\/>/)
 assert.match(wizard,/onSubmit=\{handleSubmit\}/)
 assert.equal((wizard.match(/<form\b/g)||[]).length,1,'one creation form, no nested SEO second form')
 assert.match(wizard,/ProductImageInput/)
 assert.match(wizard,/title_bn/)
 assert.match(wizard,/description_bn/)
 assert.match(wizard,/verification_notes/)
 assert.match(wizard,/q_bn_/)
 assert.match(wizard,/gallery/)
 assert.match(wizard,/marketing/)
 assert.match(wizard,/Create product & save SEO draft/)
})
test('master and SEO creation is one authorized DB transaction and leaves publication draft',()=>{
 assert.match(actions,/admin_create_product_with_seo/)
 assert.match(actions,/requireAdmin/)
 assert.match(actions,/validateProductImage/)
 assert.match(actions,/publicShowcaseImageUrl/)
 assert.match(actions,/objectPaths\.push\(objectPath\)/)
 assert.match(actions,/const cleanup=async/)
 assert.match(sql,/insert into public\.products/)
 assert.match(sql,/perform public\.admin_save_product_seo/)
 assert.doesNotMatch(sql,/update\s+private\.commerce_configuration|production_purchases_enabled\s*=\s*true/)
})
test('permanent deletion requires strict super admin and complete FK usage check',()=>{
 assert.match(sql,/private\.has_role\(v_user,'super_admin'\)/)
 assert.match(sql,/pg_constraint c/)
 assert.match(sql,/c\.confrelid='public\.commerce_skus'::regclass/)
 assert.match(sql,/delete from public\.commerce_skus where product_id=p_product_id/)
 assert.match(sql,/c\.confrelid='public\.products'::regclass/)
 assert.match(sql,/Delete blocked by usage\/history/)
 assert.match(sql,/delete from public\.products where id=p_product_id/)
 assert.match(sql,/product_deletion_audit/)
 assert.match(actions,/confirm_sku/)
 assert.match(lifecycle,/Delete unused product permanently/)
 assert.match(lifecycle,/Archive \/ deactivate/)
 assert.match(page,/eligibilityByProduct/)
})
test('archiving preserves the master and removes its SEO publication',()=>{
 assert.match(sql,/update public\.products set active=false/)
 assert.match(sql,/update public\.product_seo_content set status='unlisted'/)
 assert.match(sql,/insert into public\.product_seo_audit/)
 assert.match(actions,/admin_product_archive/)
 assert.match(actions,/remove\(\[pathname\]\)/)
})
