import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const action=read('app/actions/product-seo.ts')
const editor=read('components/admin-product-seo-editor.tsx')
const page=read('app/admin/products/page.tsx')

test('review requests save current form values first, instead of submitting stale persisted drafts',()=>{
 assert.match(editor,/onSubmit=\{handleSave\}/)
 assert.match(editor,/event\.preventDefault\(\)/)
 assert.match(editor,/new FormData\(formRef\.current\)/)
 assert.match(editor,/fd\.set\('editor_intent',intent\)/)
 assert.match(editor,/Save & submit for independent review/)
 assert.doesNotMatch(editor,/<form action=\{submitProductSeo\}/)
 assert.match(action,/p_data:\{\.\.\.parsed\.data,expected_version:/)
 const savePos=action.indexOf("supabase.rpc('admin_save_product_seo'")
 const submitPos=action.indexOf("supabase.rpc('admin_submit_product_seo'",savePos)
 assert.ok(savePos>0&&submitPos>savePos,'review submission must be after a successful database save')
})
test('validation and network failures stay inline without losing unsaved text or making synthetic claims',()=>{
 assert.match(action,/reviewBlockers\(/)
 assert.match(action,/verification_notes','Internal supplier facts/)
 assert.match(action,/Product is Inactive/)
 assert.match(action,/Demo\/test product cannot be published/)
 assert.match(action,/Upload a genuine master product image/)
 assert.match(action,/field:blockers\.some/)
 assert.match(action,/Your changes were SAVED as a draft/)
 const saveArea=action.slice(action.indexOf('export async function saveProductSeo'),action.indexOf('export async function submitProductSeo'))
 assert.doesNotMatch(saveArea,/\bredirect\(/)
 assert.doesNotMatch(saveArea,/\bfail\(/)
 assert.match(editor,/role=\{feedback\.ok\?'status':'alert'\}/)
 assert.match(editor,/setFeedback\(result\)/)
 assert.match(editor,/new FormData/)
 assert.match(editor,/sessionStorage\.setItem/)
 assert.match(editor,/sessionStorage\.getItem/)
 assert.match(editor,/sessionStorage\.removeItem/)
 assert.match(editor,/draft\.version!==\(seo\?\.version\?\?0\)/)
 assert.match(editor,/router\.refresh\(\)/)
 assert.match(page,/AdminProductSeoEditor/)
})
test('review and publishing security is unchanged; gallery slot positions retain their identities',()=>{
 assert.match(action,/admin_review_product_seo/)
 assert.match(action,/requireAdmin\(\)/)
 assert.match(editor,/m\.position===i/)
 assert.match(editor,/Independent reviewer note/)
 assert.match(editor,/canReview&&seo\.edited_by!==currentUser/)
 assert.doesNotMatch(editor,/Production purchases enabled|enableCheckout/)
})
