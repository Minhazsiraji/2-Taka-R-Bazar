import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const sql=readFileSync('supabase/migrations/20261022160100_simple_deal_joins.sql','utf8')
const action=readFileSync('app/actions/simple-offer-joins.ts','utf8')
const card=readFileSync('components/home-card-preview.tsx','utf8')
const detail=readFileSync('components/home-preview-product-details.tsx','utf8')
const badge=readFileSync('components/header-cart-count.tsx','utf8')
test('cart badge is not swallowed by locked header span selector',()=>{
 const css=readFileSync('app/public-app-design.css','utf8')
 assert.match(css,/market-header-quick-link>span/)
 assert.match(badge,/return <div className="notification-unread-badge/)
 assert.doesNotMatch(badge,/return <span className="notification-unread-badge/)
 assert.match(badge,/2tbr-cart-updated/)
})
test('join and leave actions require true authenticated account community; never count cart-only events',()=>{
 assert.match(sql,/auth\.uid\(\)/)
 assert.match(sql,/onboarding_completed_at is not null/)
 assert.match(sql,/p_area<>nominal/)
 assert.match(sql,/c\.active/)
 assert.match(sql,/unique\(offer_id,product_id,customer_id\)/)
 assert.match(sql,/pg_advisory_xact_lock/)
 assert.match(sql,/status='active'/)
 assert.match(sql,/status='cancelled'/)
 assert.match(sql,/revoke all on table public\.simple_sale_offer_joins from public,anon,authenticated/)
 assert.match(sql,/grant execute on function public\.join_simple_sale_group_deal[^;]* to authenticated/)
 assert.match(sql,/select j\.customer_id from public\.simple_sale_offer_joins/)
 assert.match(sql,/union[\s\S]*select ord\.customer_id/)
 assert.doesNotMatch(sql,/localStorage|addLaunchItem|readLaunchCart/)
})
test('join is independent of checkout and supplies meaningful unread customer notification',()=>{
 assert.match(sql,/group_deal_joined/)
 assert.match(sql,/on conflict\(user_id,dedupe_key\) do update/)
 assert.match(sql,/not a placed order or payment/)
 assert.match(action,/db\.auth\.getUser\(\)/)
 assert.match(action,/join_simple_sale_group_deal/)
 assert.match(action,/leave_simple_sale_group_deal/)
 assert.match(card,/joinSimpleSaleDeal/)
 assert.match(card,/result\.ok/)
 assert.match(card,/2tbr-notifications-refresh/)
 assert.match(detail,/joinSimpleSaleDeal/)
})
