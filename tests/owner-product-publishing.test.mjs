import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const migration=read('supabase/migrations/20261015232700_owner_direct_product_publication_issue96.sql')
const page=read('app/admin/products/page.tsx')
const editor=read('components/admin-product-seo-editor.tsx')
const actions=read('app/actions/product-seo.ts')
const sql=read('supabase/tests/owner-product-publication.sql')

test('owner is an identity-bound authority, not blanket Super Admin privilege',()=>{
 assert.match(migration,/private\.platform_owner_identity/)
 assert.match(migration,/owner_user_id uuid not null unique/)
 assert.match(migration,/private\.has_role\(p_user,'super_admin'\)/)
 assert.match(migration,/private\.is_platform_owner\(auth\.uid\(\)\)/)
 assert.match(migration,/revoke all on private\.platform_owner_identity from public, anon, authenticated/)
 assert.match(migration,/on conflict \(singleton\) do nothing/)
 assert.match(migration,/count\(\*\) from public\.user_roles where role='super_admin'/)
 assert.match(sql,/Another Super Admin cannot use owner direct publication/)
})
test('owner direct publication is an audited DB-gated decision; staff still needs review',()=>{
 assert.match(migration,/v_owner and r\.edited_by=v_user/)
 assert.match(migration,/r\.status='review'/)
 assert.match(migration,/not exists\(select 1 from public\.products/)
 assert.match(migration,/p\.active and not p\.is_demo and p\.image_url is not null/)
 assert.match(migration,/length\(btrim\(r\.verification_notes\)\)<10/)
 assert.match(migration,/status='published'/)
 assert.match(migration,/status='review'/)
 assert.match(migration,/insert into public\.product_seo_audit/)
 assert.doesNotMatch(migration,/drop table|truncate table|delete from public\.products|update public\.orders/i)
 assert.doesNotMatch(migration,/finance_review|procurement_review|treasury_review|commerce_review/)
 assert.match(sql,/Even owner cannot publish missing genuine photo/)
 assert.match(sql,/Non-owner Super Admin cannot approve their own content/)
})
test('only server-verified owner sees Save & publish; others retain independent review',()=>{
 assert.match(page,/supabase\.rpc\('is_current_platform_owner'\)/)
 assert.match(page,/isOwner=\{isOwner\}/)
 assert.match(editor,/isOwner\?'Save & publish now':'Save & submit for independent review'/)
 assert.match(editor,/seo\.edited_by===currentUser/)
 assert.match(actions,/submittedRow\.status==='published'/)
 assert.match(actions,/admin_submit_product_seo/)
 assert.match(editor,/Save SEO draft/)
 assert.doesNotMatch(actions,/service_role|SERVICE_ROLE_KEY/)
})
