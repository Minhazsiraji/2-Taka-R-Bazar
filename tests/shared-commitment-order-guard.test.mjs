import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const guard=readFileSync('supabase/migrations/20261022214500_block_premature_shared_orders.sql','utf8')
const legacy=readFileSync('supabase/migrations/20261022215000_identify_legacy_shared_requests.sql','utf8')
const cart=readFileSync('components/launch-cart-checkout.tsx','utf8')
const pool=readFileSync('components/home-preview-pool-details.tsx','utf8')
const join=readFileSync('app/actions/simple-offer-joins.ts','utf8')
const orderPage=readFileSync('app/launch-orders/[id]/page.tsx','utf8')
test('database rejects a prematurely requested Pool or Deal order before item insertion and stock decrement',()=>{
 assert.match(guard,/before insert or update of offer_id on public\.launch_order_items/)
 assert.match(guard,/k in \('GROUP_DEAL','COMMUNITY_POOL'\)/)
 assert.match(guard,/raise exception 'Group Deal and Pool are commitments only/)
 assert.match(guard,/new\.offer_id is null then return new/)
 assert.match(guard,/do not modify existing orders or inventory/i)
})
test('existing preliminary Pool orders cannot be staff-approved or marked paid',()=>{
 assert.match(guard,/exists\(select 1 from public\.launch_order_items/i)
 assert.match(guard,/new\.status='confirmed' or new\.payment_status is distinct from old\.payment_status/)
 assert.match(guard,/before update of status,payment_status on public\.launch_orders/)
 assert.match(legacy,/o\.customer_id=auth\.uid\(\)/)
 assert.match(orderPage,/launch_order_has_unsettled_shared_item/)
 assert.match(orderPage,/Do not send payment/)
 assert.match(orderPage,/!legacyShared&&order\.status==='confirmed'/)
})
test('shared cart is a commitment estimate and never offers checkout',()=>{
 assert.match(cart,/const hasShared=lines\.some/)
 assert.match(cart,/hasShared\?\'Current estimate/)
 assert.match(cart,/!checkout&&!hasShared&&<Link/)
 assert.match(cart,/\{checkout&&!hasShared&&/)
 assert.match(cart,/Removing a cart item does not cancel the registered commitment/)
 assert.doesNotMatch(cart,/leaveSimpleSaleDeal/)
})
test('Pool and Group Deal clearly say final consent precedes payment',()=>{
 assert.match(pool,/Join Pool · Save commitment/)
 assert.match(pool,/Joining saves a commitment, not an order/)
 assert.match(join,/Wait for the final tier and delivery quote/)
 assert.match(join,/A finalized quote and your explicit acceptance/)
})

test('commitment products and quantities are held securely without stock or checkout writes',()=>{
 const sql=readFileSync('supabase/migrations/20261022222500_persist_commitment_quantities.sql','utf8')
 const action=readFileSync('app/actions/simple-offer-joins.ts','utf8')
 assert.match(sql,/simple_sale_commitment_items/)
 assert.match(sql,/quantity integer not null check\(quantity between 1 and 100\)/)
 assert.match(sql,/enable row level security/)
 assert.match(sql,/revoke all on public\.simple_sale_commitment_items from public,anon,authenticated/)
 assert.match(sql,/customer_id=\(select auth\.uid\(\)\)/)
 assert.match(sql,/join_simple_sale_group_deal_quantified/)
 assert.match(sql,/join_simple_sale_pool_quantified/)
 assert.match(sql,/set_simple_sale_commitment_quantity/)
 assert.match(action,/db\.rpc\('join_simple_sale_group_deal_quantified'/)
 assert.match(action,/db\.rpc\('join_simple_sale_pool_quantified'/)
 assert.match(action,/db\.rpc\('set_simple_sale_commitment_quantity'/)
 assert.doesNotMatch(sql,/insert into public\.launch_orders|update public\.launch_product_stock|payment_reference/)
})
