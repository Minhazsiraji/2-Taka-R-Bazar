import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=(p)=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const page=read('app/page.tsx')
const market=read('components/public-marketplace.tsx')
const header=read('components/public-header.tsx')
const lower=read('components/public-marketplace-lower.tsx')
const fixtures=read('lib/public-demo-products.ts')
const details=read('app/demo-product/[id]/page.tsx')
const detailsClient=read('components/demo-product-details.tsx')
const css=read('app/marketplace-flat.css')
test('Bangla storefront is default and language switching applies throughout homepage',()=>{
 assert.match(market,/useState<MarketplaceLanguage>\('bn'\)/)
 assert.match(header,/onLanguageChange/)
 assert.match(header,/language==='bn'\?'EN':'BAN'/)
 assert.match(header,/market-single-language/)
 assert.match(market,/language=\{language\}/)
 assert.match(lower,/chooseText\(language,en,bn\)/)
 assert.match(header,/কমিউনিটিতে যোগ দিন/)
 assert.match(lower,/সাধারণ প্রশ্নোত্তর/)
})
test('banner removed and community panel compact, with GPS/manual fallback',()=>{
 assert.doesNotMatch(market,/Storefront offers are being configured/)
 assert.match(market,/market-location-panel/)
 assert.match(market,/getCurrentPosition/)
 assert.match(market,/selectArea\(e.target.value\)/)
 assert.match(css,/market-location-panel/)
})
test('illustrated sample product data only appears on Preview or in development',()=>{
 assert.match(fixtures,/VERCEL_ENV === 'preview'/)
 assert.match(fixtures,/VERCEL_ENV !== 'production'/)
 assert.match(fixtures,/DEMO_OFFERS/)
 assert.match(fixtures,/DEMO_SHOWCASE/)
 assert.match(fixtures,/is_demo:true/)
 assert.match(page,/demoStorefrontEnabled\(\)/)
 assert.match(market,/offer.is_demo/)
 assert.match(market,/disabled aria-disabled="true"/)
 assert.match(details,/if\(!demoStorefrontEnabled\(\)\)notFound\(\)/)
 assert.match(detailsClient,/disabled type="button"/)
 assert.match(details,/robots:\{index:false,follow:false\}/)
})
test('sample cards, carousel and public area filtering are wired',()=>{
 assert.match(market,/demo-product\/\$\{offer.product_id\}/)
 assert.match(market,/formatPrice\(offer.solo_price\)/)
 assert.match(market,/formatPrice\(offer.confirmed_price/)
 assert.match(market,/FeaturedProductsCarousel products=\{featured\} language=\{language\}/)
 assert.match(lower,/\/demo-product\//)
})
