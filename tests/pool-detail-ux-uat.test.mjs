 assert.match(pool,/onClick=\{addBundle\}/)
 assert.match(pool,/demoPoolBasketTotal\(pool,threshold,quantities\)/)
 assert.match(pool,/itemCount===0\?'৳0'/)
 assert.doesNotMatch(pool,/onClick=\{\(\)=>addOne\(/)
