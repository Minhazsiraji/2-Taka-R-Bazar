import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=(path)=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const demoPage=read('app/demo-pool/[slug]/page.tsx')
const pool=read('components/demo-pool-detail.tsx')
const featured=read('lib/featured-pools.ts')
const showcase=read('components/featured-pool-showcase.tsx')
const catalog=read('components/public-marketplace.tsx')
const style=read('app/pool-detail-refinement.css')

test('home offers all products until selected area then filters strictly',()=>{
 assert.match(catalog,/browseCatalogOffers\(offers,\{area,mode,category,search\}\)/)
 assert.match(catalog,/!area\?<div className="market-product-actions/)
 assert.match(catalog,/selectArea\(offer.community_id\)/)
 assert.match(catalog,/categories=useMemo\(\(\)=>\[\.\.\.new Set\(offers\.filter\(o=>!area\|\|o\.community_id===area\)/)
 assert.match(catalog,/getCommunityDemoFeaturedPools\(offers,area\)/)
})
test('selected demo Pool opens with only its chosen community package',()=>{
 assert.match(featured,/getCommunityDemoFeaturedPools\(offers:StorefrontOffer\[\],selectedArea=''/)
 assert.match(featured,/offers\.filter\(offer=>offer\.community_id===selectedArea\)/)
 assert.match(featured,/community_id:selectedArea/)
 assert.match(showcase,/selectedArea\?'\?area='/)
 assert.match(demoPage,/DEMO_AREAS\.some\(a=>a\.community_id===requestedArea\)/)
 assert.match(demoPage,/getCommunityDemoFeaturedPools\(DEMO_OFFERS,selectedArea\)/)
 assert.match(pool,/communityName&&<p className="market-demo-area-pill"/)
})
